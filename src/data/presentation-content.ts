export function extractHeading(section: string): string {
  const m = section.match(/^# (.+)$/m);
  return m ? m[1] : '';
}

export function extractSubheading(section: string): string {
  const m = section.match(/^## (.+)$/m);
  return m ? m[1] : '';
}

export function extractBlockquote(section: string): string {
  const m = section.match(/^> (.+)$/m);
  return m ? m[1] : '';
}

export function extractItalic(section: string): string {
  const m = section.match(/^\*(.+)\*$/m);
  return m ? m[1] : '';
}

/** Lines starting with `- ` — returns raw line content after the dash */
export function extractListItems(section: string): string[] {
  const lines = section.split('\n');
  return lines
    .filter((l) => l.match(/^- /))
    .map((l) => l.replace(/^- /, '').trim());
}

/**
 * Parse a list item like `**Title**: Description` into { title, text }.
 * Falls back to full string as title if no bold found.
 */
export function parseListItem(item: string): { title: string; text: string } {
  const m = item.match(/^\*\*(.+?)\*\*[:\s]*(.*)$/);
  if (m) return { title: m[1], text: m[2] };
  return { title: item, text: '' };
}

/**
 * Parse a tradeoff item like `**Versus** | Decision | Why`
 */
export function parseTradeoffItem(item: string): {
  versus: string;
  decision: string;
  why: string;
} {
  const m = item.match(/^\*\*(.+?)\*\*\s*\|\s*(.+?)\s*\|\s*(.+)$/);
  if (m) return { versus: m[1], decision: m[2], why: m[3] };
  return { versus: item, decision: '', why: '' };
}

/**
 * Parse a roadmap item like `**Title** [Status]: Description`
 */
export function parseRoadmapItem(item: string): {
  title: string;
  status: string;
  desc: string;
} {
  const m = item.match(/^\*\*(.+?)\*\*\s*\[(.+?)\][:\s]*(.*)$/);
  if (m) return { title: m[1], status: m[2], desc: m[3] };
  return { title: item, status: '', desc: '' };
}

/**
 * Parse a workflow item like `` `/cmd`: Description ``
 */
export function parseWorkflowItem(item: string): {
  cmd: string;
  desc: string;
} {
  const m = item.match(/`(.+?)`[:\s]*(.+)$/);
  if (m) return { cmd: m[1], desc: m[2] };
  return { cmd: item, desc: '' };
}

/** Lines matching `| value | label |` */
export function extractTableRows(
  section: string,
): Array<{ value: string; label: string }> {
  const lines = section.split('\n');
  return lines
    .filter((l) => l.match(/^\|/))
    .map((l) => {
      const cells = l
        .split('|')
        .map((c) => c.trim())
        .filter(Boolean);
      return { value: cells[0] || '', label: cells[1] || '' };
    });
}

/**
 * Extract "plain" paragraphs — lines that are NOT headings, list items,
 * blockquotes, italic, or table rows.
 */
export function extractParagraphs(section: string): string[] {
  return section
    .split('\n')
    .filter(
      (l) =>
        l.trim() &&
        !l.match(/^#+ /) &&
        !l.match(/^- /) &&
        !l.match(/^> /) &&
        !l.match(/^\*.*\*$/) &&
        !l.match(/^\|/),
    )
    .map((l) => l.trim());
}

/**
 * Extract comma-separated items from a plain line (for cycle steps)
 */
export function extractCommaSeparated(section: string): string[] {
  const paragraphs = extractParagraphs(section);
  // Find the line with commas (the steps line)
  const stepsLine = paragraphs.find((p) => p.includes(','));
  if (!stepsLine) return [];
  return stepsLine.split(',').map((s) => s.trim());
}

