export function getStoredMarkdown(): string {
  if (typeof window === 'undefined') return defaultMarkdown;
  return localStorage.getItem(STORAGE_KEY) || defaultMarkdown;
}

export function setStoredMarkdown(markdown: string): void {
  if (typeof window === 'undefined') return;
  localStorage.setItem(STORAGE_KEY, markdown);
}

export function clearStoredMarkdown(): void {
  if (typeof window === 'undefined') return;
  localStorage.removeItem(STORAGE_KEY);
}
